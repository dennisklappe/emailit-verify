// Regenerates src/client-source.ts from client/client.js (v2, the alias) and client/client.v1.js (frozen v1).
import { readFileSync, writeFileSync } from "node:fs";
const read = (f) => readFileSync(new URL(f, import.meta.url), "utf8");
writeFileSync(
	new URL("../src/client-source.ts", import.meta.url),
	`// Generated by \`npm run build:client\` from client/*.js. Do not edit.\nexport const CLIENT_JS = ${JSON.stringify(read("../client/client.js"))};\nexport const CLIENT_V1 = ${JSON.stringify(read("../client/client.v1.js"))};\n`,
);
